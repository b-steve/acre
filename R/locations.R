#' Calculate location density
#'
#' Calculates the estimated density of a location, given its observed capture
#' history and auxiliary information.
#'
#' @param fit an object generated from the model fitting function
#'    [fit.acre] or the bootstrap process [boot.acre].
#' @param call.id an numeric vector indicating which call ID's to calculate
#'    density for.
#' @param animal.id an numeric value indicating animal ID. Should only be
#'    specified if `fit` is an `animalID` model.
#' @param session an integer value indicating the session of detector array and
#'    individual(s) to be plotted.
#' @param mask a list or a data frame. Generated by [create.mask()].
#' @param warn.toa a logical value indicates whether to issue warning in the
#'    case of `toa` data with only a single call.
#' @param newdata data.frame; contains any covariates that will be used
#'    for all extended parameters.
#' @return (Still to write)
#' @export
location.density <- function(fit, call.id, animal.id=NULL, session=1,
                             mask=get.mask(fit)[[session]], warn.toa=F,
                             newdata=NULL) {
  ## Note that input validation for call.id, animal.id and session
  ## is handled in `get.capt.by.id()`.

  density_types <- c(fit$infotypes, "capt", "Dsurface")

  if ("ss" %in% density_types) {
    ## stop("Combined density plotting is not currently implemented for signal
    ## strength models.")
    density_types <- density_types[which(density_types != "capt")]
  }

  ## Note that each density function returns a data frame with columns:
  ## ID, x, y, [density_name]_density.
  density_list <- lapply(density_types, function(d.type) {
    switch(
      d.type,
      "Dsurface" = Dsurface.density(fit, session, mask),
      "capt" = capt.density(fit, call.id, animal.id, session, mask),
      "toa"  = toa.density(fit, call.id, animal.id, session, mask,
                           warn=warn.toa),
      "dist" = dist.density(fit, call.id, animal.id, session, mask),
      "ss"   = ss.density(fit, call.id, animal.id, session, mask),
      "bearing" = bearing.density(fit, call.id, animal.id, session, mask),
      stop(paste0("Unknown density type: '", d.type,
                  "', currently supported types are: 'capt', 'ss', 'dist',
                   'bearing', 'toa', 'Dsurface'."))
    )
  })

  ## For clarity.
  names(density_list) <- density_types

  ## Keep the three key columns only once.
  base_cols <- density_list[[1]][, c("ID", "x", "y")]

  ## Pull the single density column from each data frame.
  dens_mat <- do.call(
    cbind,
    lapply(density_list, `[`, "z")
  )

  ## Rename those columns to match the density types.
  colnames(dens_mat) <- paste0(density_types, "_density")

  ## Final data frame.
  merged_densities <- cbind(base_cols, dens_mat)

  ## Create the combined density column by multiplying all density columns.
  merged_densities$combined_density <- Reduce(`*`, merged_densities[-c(1:3)])

  ## Return the final data frame.
  return(merged_densities)
}


## The density of each call's location from one type of data, as a data frame with columns ID, x, y
## and z. The function call.fun(det, bin, s) gives the density at each mask point for one call, from
## its detections (det, the call's rows of the captures, sorted by detector), its binary capture
## history (bin, one element per detector), and the session's set-up (s: the detection parameters,
## with extended parameters as n.traps x n.mask matrices, the detectors, and the detector-mask
## distances).
call.density <- function(fit, type, call.id, animal.id, session, mask, call.fun, newdata = NULL) {
  ## The function get.capt.by.id() validates `call.id`, `animal.id` and `session`.
  if (!type %in% c("capt", fit$infotypes)) {
    stop(paste0("'fit' does not contain '", type, "' information. ",
                "Infotypes available for the fit provided are: ",
                paste0(fit$infotypes, collapse=", "), ", Dsurface, capt"))
  }
  capt <- get.capt.by.id(fit, call.id, animal.id, session)
  traps <- get.trap(fit)[[session]]

  ## Only allow the newdata argument for parameter-extended models.
  par_extended <- !is.null(get.par.extend(fit))
  if (!is.null(newdata) && !par_extended) {
    stop("'newdata' argument is only available for parameter extended models")
  }
  det_pars <- as.list(coef(fit, type="fitted"))
  if (par_extended) {
    ## Calculate the parameter values for each mask point-trap combination.
    ext_par_matrices <- get.par.extend.matrix(fit, mask, traps, session = session, newdata = newdata)
    det_pars[names(ext_par_matrices)] <- ext_par_matrices
  }

  ## Calculate mask-trap distances.
  dists <- distances(traps, as.matrix(mask))
  ## If a trap is exactly on a mask point, the distance will be 0, causing numerical issues.
  dists[dists == 0] <- .Machine$double.eps
  s <- list(pars = det_pars, traps = traps, dists = dists)

  if (identical(call.id, "all")) call.id <- unique(capt$ID)
  density_list <- lapply(call.id, function(cid) {
    det <- capt[capt$ID == cid, ]
    det <- det[order(det$trap), ]
    bin <- numeric(nrow(traps))
    bin[det$trap] <- 1
    data.frame(ID = cid, x = mask[, 1], y = mask[, 2], z = call.fun(det, bin, s))
  })
  do.call(rbind, density_list)
}

## The product over detectors (rows) of densities at each mask point (columns); a vector is a
## single detector's densities.
prod.over.traps <- function(dens) {
  if (is.matrix(dens)) matrixStats::colProds(dens) else dens
}

## A detection parameter's values for some detectors: rows of its matrix if it is extended,
## otherwise the scalar.
trap.par <- function(par, traps) {
  if (is.matrix(par)) par[traps, ] else par
}

dist.density <- function(fit, call.id, animal.id=NULL, session=1,
                         mask=get.mask(fit)[[session]]) {
  call.density(fit, "dist", call.id, animal.id, session, mask, function(det, bin, s) {
    ## Keep only detectors with a non-missing recorded distance.
    det <- det[!is.na(det$dist), ]
    if (nrow(det) == 0) return(rep(1, nrow(mask)))
    alpha <- trap.par(s$pars$alpha, det$trap)
    prod.over.traps(dgamma(det$dist, shape = alpha, rate = alpha/s$dists[det$trap, ]))
  })
}

bearing.density <- function(fit, call.id, animal.id=NULL, session=1,
                            mask=get.mask(fit)[[session]]) {
  mask_bearings <- bearings(get.trap(fit)[[session]], as.matrix(mask))
  call.density(fit, "bearing", call.id, animal.id, session, mask, function(det, bin, s) {
    ## Keep only detectors with a non-missing recorded bearing.
    det <- det[!is.na(det$bearing), ]
    if (nrow(det) == 0) return(rep(1, nrow(mask)))
    prod.over.traps(CircStats::dvm(det$bearing, mu = mask_bearings[det$trap, ],
                                   kappa = trap.par(s$pars$kappa, det$trap)))
  })
}

toa.density <- function(fit, call.id, animal.id=NULL, session=1,
                        mask=get.mask(fit)[[session]], warn=T) {
  single_trap_detection <- FALSE
  out <- call.density(fit, "toa", call.id, animal.id, session, mask, function(det, bin, s) {
    ## Keep only detectors with a non-missing recorded TOA; at least 2 are needed to be able
    ## to use arrival time data.
    det <- det[!is.na(det$toa), ]
    if (nrow(det) < 2) {
      single_trap_detection <<- TRUE
      return(rep(1, nrow(mask)))
    }
    prod.times <- det$toa - s$dists[det$trap, ]/fit$args$sound.speed
    toa.ssq <- apply(prod.times, 2, function(x) sum((x - mean(x))^2))
    ## The parameter sigma.toa has no detector-level covariates, so if it is extended, all of
    ## its rows are the same.
    sigma_toa <- s$pars$sigma.toa
    if (is.matrix(sigma_toa)) sigma_toa <- sigma_toa[1, ]
    (2*pi*sigma_toa^2)^((1 - nrow(det))/2)*exp(toa.ssq/(-2*sigma_toa^2))
  })
  if (warn & single_trap_detection) {
    warning(paste("Some calls were detected by only a single trap.
    The use of toa data requires a call to be detected by at least
    2 traps. Toa density for corresponding calls has been set to 1
                  across the entire mask for such cases."))
  }
  out
}

ss.density <- function(fit, call.id, animal.id=NULL, session=1,
                       mask=get.mask(fit)[[session]], newdata=NULL) {
  cutoff <- get.ss.opts(fit)$cutoff
  call.density(fit, "ss", call.id, animal.id, session, mask, newdata = newdata, function(det, bin, s) {
    triggered <- det$trap
    untriggered <- which(bin == 0)
    ## The expected signal strength, and its standard deviation, for some detectors.
    mu.ss <- function(traps) trap.par(s$pars$b0.ss, traps) - trap.par(s$pars$b1.ss, traps)*s$dists[traps, ]
    sd.ss <- function(traps) trap.par(s$pars$sigma.ss, traps)
    ## The density of the signal strengths at the detectors that were triggered, and the
    ## probability of being below the cutoff at those that were not.
    mask.dens <- matrix(1, nrow = length(bin), ncol = nrow(mask))
    mask.dens[triggered, ] <- dnorm(det$ss, mu.ss(triggered), sd.ss(triggered))
    mask.dens[untriggered, ] <- pnorm(cutoff, mu.ss(untriggered), sd.ss(untriggered))
    matrixStats::colProds(mask.dens)
  })
}

capt.density <- function(fit, call.id, animal.id=NULL, session=1,
                         mask=get.mask(fit)[[session]]) {
  detfn <- get.detfn(fit)
  if (fit$fit.types["ss"] || detfn == 'ss') {
    stop("Capture density for signal strength models is built in to the
         signal strength density. Please use 'ss.density()' instead.")
  }
  call.density(fit, "capt", call.id, animal.id, session, mask, function(det, bin, s) {
    ## Probability of detection at each mask point. Note that det.prob() is set up so that
    ## we can pass n_traps x n_mask matrices as parameter values, and get the corresponding
    ## n_traps x n_mask detection probabilities back.
    det.probs <- det.prob(detfn, s$pars, s$dists)
    ## Density due to capture history alone.
    apply((det.probs ^ bin) * ((1 - det.probs) ^ (1 - bin)), 2, prod)
  })
}

Dsurface.density <- function(fit, session=1, mask=get.mask(fit)[[session]]) {
  ## Grab the estimated parameters, along with other model fitting variables.
  det_pars <- as.list(coef(fit, type="fitted"))
  detfn <- get.detfn(fit)
  if (fit$fit.types["ss"]) {
    det_pars$cutoff <- get.ss.opts(fit)$cutoff
  }
  ss_link <- get.ss.link(fit)
  traps <- get.trap(fit)[[session]]
  a <- attr(mask, "area")

  par_extended <- !is.null(get.par.extend(fit))

  ## Deal with extended parameters.
  if (par_extended) {
    ext_par_matrices <- get.par.extend.matrix(fit, mask, traps, session = session)
    det_pars[names(ext_par_matrices)] <- ext_par_matrices
  }

  ## Calculate detection probabilities.
  prob_det_total <- p.dot.defaultD(as.matrix(mask), traps, detfn, ss_link,
                                   det_pars, a)
  prob_det <- p.dot.defaultD(as.matrix(mask), traps, detfn, ss_link, det_pars, a,
                             esa = F)

  ## Calculate the location density.
  if (fit$fit.ihd){
    if (TRUE) { ## is.null(newdata)
      ## Note that the intensity mask is simply our estimated density at each mask
      ## point.
      intensity_mask <- fit$D.mask[[session]]
    } else {
      ## Density cannot be extended at the trap level, so take the first row, as all the
      ## rows will be identical.
      intensity_mask <- det_pars$D[1, ]
    }
    z <- (prob_det * intensity_mask) / (a * sum(prob_det * intensity_mask))
  } else {
    ## Note that prob_det_total is already multiplied by `a` in p.dot.defaultD().
    z <- prob_det / prob_det_total
  }

  density.df <- data.frame(
    x = mask[, 1],
    y = mask[, 2],
    z = z
  )

  return(density.df)
}

contours.plot <- function(x, y, dens, n.levels, filled=FALSE, ...) {
  ## Prepare data for contour plotting;
  ## this requires no duplicate x or y.
  unique.x <- sort(unique(x))
  unique.y <- sort(unique(y))

  ## Assign every x, y to the corresponding matrix row/column;
  ## match() returns the first position where the values match.
  row_id <- match(x, unique.x)
  col_id <- match(y, unique.y)

  ## Assign each density to the corresponding matrix index.
  z <- matrix(NA_real_, nrow = length(unique.x), ncol = length(unique.y))
  z[cbind(row_id, col_id)] <- dens

  ## I tried using pretty(), but its inconsistent output is annoying.
  dens_range <- range(dens)
  levels <- seq(from = dens_range[1], to = dens_range[2],
                length.out = n.levels + 1)

  ## Convert density breaks to probabilities;
  ## raw density levels aren't meaningful to the typical user.
  probability_labels <- character(n.levels + 1)
  for (i in 1:(n.levels + 1)){
    probability_labels[i] <- format(
      round(sum(dens[dens > levels[i]]) / sum(dens), 2),
      nsmall = 2)
  }

  ## Plot the contours.
  if (filled) {
    ## Interpolate to a grid for higher resolution.
    grid <- list(
      x = seq(min(unique.x), max(unique.x), length = 500),
      y = seq(min(unique.y), max(unique.y), length = 500)
    )

    surf <- fields::interp.surface.grid(
      obj  = list(x = unique.x, y = unique.y, z = z),
      grid = grid
    )

    ## Without the grid: fields::imagePlot(x = unique.x, y = unique.y, z = z, ...).
    fields::imagePlot(x = grid$x, y = grid$y, z = surf$z,
                      col = faded.virdis(n.levels),
                      xlim = range(x), ylim = range(y),
                      xlab = "x", ylab = "y",
                      legend.width = 2, legend.line = 4,
                      legend.lab = "Probability", legend.shrink = 1,
                      legend.mar = 6,
                      breaks = levels, lab.breaks = probability_labels)

    contour(x = unique.x, y = unique.y, z = z, levels = levels,
            labels = probability_labels, add = TRUE,
            col=faded.virdis(n.levels, max.alpha = 0.6),
            lwd=1, drawlabels = F, ...)

  } else {
    contour(x = unique.x, y = unique.y, z = z, levels = levels,
            labels = probability_labels, drawlabels = TRUE, add = TRUE,
            asp=1, ...)
  }
}

locations.plot <- function(fit, call.id = NULL, animal.id = NULL, session=1,
                           filled=FALSE, n.levels=8, add=FALSE) {
  if (add & filled) {
    stop("filled contours cannot be added to existing plots")
  }
  ## If `call.id` is not passed, assume we want to plot all the unique calls.
  if (is.null(call.id)) {
    call.id <- unique(get.capt.by.id(fit, "all", animal.id, session)$ID)
  }

  mask <- get.mask(fit)[[session]]

  for (cid in call.id) {
    ## Calculate the densities for this call.
    dens <- location.density(fit, cid, animal.id, session = session)

    ## Plot the density contours.
    if (filled) {
      contours.plot(dens$x, dens$y, dens$combined_density, n.levels, filled = TRUE)
    } else {
      if (!add) {
        plot(NA, xlim = range(mask[, 1]), ylim = range(mask[, 2]), asp = 1,
             xlab = "x", ylab = "y")
      }
      contours.plot(dens$x, dens$y, dens$combined_density, n.levels)
    }

    ## Plot all the additional capture information:
    ## traps.
    traps.plot(fit, cid, animal.id, session)
    ## Bearing arrows.
    if ("bearing" %in% fit$infotypes) {
      bearing.arrows.plot(fit, cid, animal.id, session)
    }
    ## Distance circles, only if there are no bearings.
    else if ("dist" %in% fit$infotypes) {
      distance.circles.plot(fit, cid, animal.id, session)
    }
    ## TOA order.
    if ("toa" %in% fit$infotypes) {
      toa.order.plot(fit, cid, animal.id, session)
    }

    ## Title.
    if (!add) {
      plot_title <- create.locations.plot.title(cid, animal.id, session)
      title(plot_title)
    }

    if (length(call.id) > 1 && cid != call.id[[length(call.id)]]) {
      ask.user.for.next.plot()
    }
  }
}

## Create a plot subtitle for locations.plot().
create.locations.plot.title <- function(call.id, animal.id, session) {
  if (is.null(animal.id)) {
    subtitle <- paste0("session: ", session, ", call ID: ", call.id)
  } else {
    if (length(call.id) == 1) {
      subtitle <- paste0("session: ", session, ", animal ID: ", animal.id,
                        ", call ID: ", call.id)
    } else {
      subtitle <- paste0("session: ", session, ", animal ID: ", animal.id)
    }
  }

  return(subtitle)
}


